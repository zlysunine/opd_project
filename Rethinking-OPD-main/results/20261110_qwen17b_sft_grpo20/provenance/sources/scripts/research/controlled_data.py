import random
import shutil
import tempfile

from .common import checkpoint_identity, digest, file_hash, read_jsonl, write_json, write_jsonl


def validate_controlled(c):
    t = c['training']
    if t['gpus'] != 1 or t['microbatch'] != 1 or t['epochs'] != 1:
        raise ValueError('Controlled v1 requires one GPU, microbatch=1 and one fixed schedule pass')
    if t['steps']*t['batch'] > c['dataset']['train_n']:
        raise ValueError('Not enough distinct train questions for the fixed schedule')
    if t['steps'] not in c['monitor']['optimizer_steps']:
        raise ValueError('The final training step must be monitored')
    if t['training_mode'] != 'lora' or t['loss_type'] != 'forward_kl':
        raise ValueError('Shared template must describe LoRA / forward-KL OPSD')
    if not c['monitor'].get('diagnostic_privileged_teacher'):
        raise ValueError('All methods must collect the same privileged-context diagnostics')
    if t.get('checkpoint_retention') not in ('all','latest'):
        raise ValueError('Controlled retention must be all, or latest with analysis before rotation and adapter archives')
    required = ('weight_decay','adam_betas','adam_eps','grad_clip','lr_scheduler')
    if any(k not in t for k in required) or t['lr_scheduler'] != 'constant':
        raise ValueError('Pin common AdamW settings and the constant learning-rate schedule')


def schedule(rows, batch, steps, seed):
    if len({r['problem_id'] for r in rows}) != len(rows):
        raise ValueError('Schedule source must contain unique question IDs')
    indices = list(range(len(rows)))
    random.Random(seed).shuffle(indices)
    if batch*steps > len(indices):
        raise ValueError('Schedule may not silently recycle questions')
    selected = [copy.deepcopy(rows[i]) for i in indices[:batch*steps]]
    groups = [dict(step=i+1, problem_ids=[r['problem_id'] for r in selected[i*batch:(i+1)*batch]])
              for i in range(steps)]
    return selected, groups


def record_exposure(schedule_path, step, ids, output):
    expected = json.loads(Path(schedule_path).read_text())['batches']
    row = next((r for r in expected if r['step'] == step), None)
    if row is None or list(ids) != row['problem_ids']:
        raise ValueError(f'Question order differs from the shared schedule at step {step}')
    target = Path(output)/f'step_{step:06d}.json'
    value = dict(row, schedule_sha256=file_hash(schedule_path))
    if target.exists() and json.loads(target.read_text()) != value:
        raise ValueError('Existing exposure receipt changed')
    write_json(target, value)


def grpo_signal(scores, uids):
    """Outcome variation, not correctness averaged across unrelated prompts."""
    import numpy as np
    grouped = {}
    for score, uid in zip(scores,uids):
        grouped.setdefault(str(uid),[]).append(float(score))
    groups = list(grouped.values())
    if not groups:
        raise ValueError('Empty GRPO groups')
    return {'grpo/zero_variance_group_fraction':float(np.mean([len(set(g))==1 for g in groups])),
            'grpo/all_zero_group_fraction':float(np.mean([all(x==0 for x in g) for g in groups])),
            'grpo/all_one_group_fraction':float(np.mean([all(x==1 for x in g) for g in groups])),
            'grpo/reward_mean':float(np.mean(scores))}


def adopt_probe(c, source, target):
    """Copy verified historical data; publish NEW provenance instead of rewriting history."""
    from analysis.common import source_hashes
    source, target = Path(source).resolve(), Path(target).resolve()
    if source == target or source in target.parents or target in source.parents:
        raise ValueError('Use a new workdir outside the source probe')
    receipt = json.loads((source/'complete.json').read_text())
    manifest = json.loads((source/'manifest.json').read_text())
    for name, expected in receipt['files'].items():
        path = (source/name).resolve()
        if source not in path.parents or not path.is_file() or file_hash(path) != expected:
            raise ValueError(f'Historical frozen file changed or unsafe: {name}')
    if receipt['probe_manifest_hash'] != file_hash(source/'probe_manifest.jsonl'):
        raise ValueError('Historical probe manifest hash mismatch')
    initial = checkpoint_identity(c['model']['path'])
    if receipt['identity'].get('checkpoint_hash') != initial:
        raise ValueError('Historical probe was generated by different base weights')
    if receipt['identity']['input_hash'] != file_hash(c['dataset']['input']):
        raise ValueError('Native dataset file differs from the historical experiment')
    for key in ('revision','reference_field','difficulty_min','difficulty_max','answer_protocol'):
        if manifest['dataset'].get(key) != c['dataset'].get(key):
            raise ValueError(f'Historical dataset/protocol mismatch: {key}')
    if manifest['model']['revision'] != c['model']['revision']:
        raise ValueError('Historical model revision differs')
    old_config=manifest['provenance']['config']
    for key in ('max_probe_response_tokens','behavior_max_response_tokens','live_greedy','anchors'):
        if old_config['monitor'].get(key)!=c['monitor'].get(key):
            raise ValueError(f'Historical monitoring protocol differs: {key}')
    for key in ('max_prompt_length','max_response_length','max_teacher_prompt_length'):
        if old_config['training'][key]!=c['training'][key]:
            raise ValueError(f'Historical data eligibility length differs: {key}')
    for split, count in [('train',c['dataset']['train_n']),('validation',c['dataset']['dev_n']),
                         ('heldout_probe',c['monitor']['heldout_probe_n']),('train_probe',c['monitor']['train_probe_n'])]:
        if len(read_jsonl(source/f'{split}.jsonl')) != count:
            raise ValueError(f'Historical split size differs: {split}')
    target.parent.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix='.adopt-', dir=target.parent) as temp:
        staging = Path(temp)/'probe'
        staging.mkdir()
        for name in receipt['files']:
            destination = staging/name; destination.parent.mkdir(parents=True, exist_ok=True)
            shutil.copy2(source/name,destination)
        write_json(staging/'adopted_source_complete.json',receipt)
        write_json(staging/'adoption_receipt.json',dict(source=str(source),source_manifest=manifest,
                   source_complete_sha256=file_hash(source/'complete.json'),
                   note='Frozen IDs/text/tokens reused verbatim; diagnostics rerun with current code. Historical training order is not reconstructed.'))
        identity = dict(config_hash=digest(c),input_hash=file_hash(c['dataset']['input']),
                        checkpoint_hash=initial,sources=source_hashes())
        write_json(staging/'complete.json',dict(identity=identity,
            files={str(p.relative_to(staging)):file_hash(p) for p in staging.rglob('*') if p.is_file()},
            probe_manifest_hash=receipt['probe_manifest_hash']))
        staging.rename(target)
    return target


def prepare_shared(c):
    from analysis.prepare_probe import freeze
    root = Path(c['output_root'])/'probe'
    if not root.exists() and c['dataset'].get('frozen_probe_source'):
        adopt_probe(c,c['dataset']['frozen_probe_source'],root)
    # freeze validates every adopted file and the new config/source identity.
    root = freeze(c)
    from transformers import AutoTokenizer,AutoConfig
    from .models import ByteTokenizer
    from .controlled_sft import encode_target
    from .common import opsd
    tokenizer=(ByteTokenizer() if (Path(c['model']['path'])/'byte_tokenizer.json').is_file()
               else AutoTokenizer.from_pretrained(c['model']['path'],local_files_only=True))
    architecture=AutoConfig.from_pretrained(c['model']['path'],local_files_only=True)
    rows = read_jsonl(root/'train.jsonl')
    splits={name:read_jsonl(root/f'{name}.jsonl') for name in ('validation','heldout_probe','train_probe')}
    ids={name:{r['problem_id'] for r in values} for name,values in dict(train=rows,**splits).items()}
    if (ids['train'] & ids['validation'] or ids['train'] & ids['heldout_probe']
            or ids['validation'] & ids['heldout_probe'] or not ids['train_probe'] <= ids['train']):
        raise ValueError('Frozen split leakage or train_probe outside train')
    for row in rows:
        if row['messages']!=opsd.plain_messages(row['question']):
            raise ValueError('All training methods require the exact unprivileged student prompt')
        prompt,response=encode_target(row,tokenizer,c['training'])
        if len(prompt)+len(response)>architecture.max_position_embeddings:
            raise ValueError('SFT target exceeds the shared model context')
    for row in read_jsonl(root/'fixed_pool.jsonl'):
        prompt=tokenizer.encode(opsd.plain_messages(row['question'])[0]['content'],add_special_tokens=False)
        if prompt!=row['prompt_ids']:
            raise ValueError('Adopted frozen prompt IDs differ from the current answer protocol')
    selected, batches = schedule(rows,c['training']['batch'],c['training']['steps'],c['training']['seed'])
    # Keep the original pool; only this deterministic prefix is fed to each trainer.
    target = root/'train_schedule.jsonl'
    if target.exists() and read_jsonl(target) != selected:
        raise ValueError('Existing controlled training order changed')
    write_jsonl(target,selected)
    write_json(root/'question_schedule.json',dict(seed=c['training']['seed'],
               pool_sha256=file_hash(root/'train.jsonl'),batches=batches,
               train_probe_exposures={r['problem_id']:[b['step'] for b in batches if r['problem_id'] in b['problem_ids']]
                                      for r in read_jsonl(root/'train_probe.jsonl')}))
    receipt = json.loads((root/'complete.json').read_text())
    for name in ('train_schedule.jsonl','question_schedule.json'):
        receipt['files'][name] = file_hash(root/name)
    write_json(root/'complete.json',receipt)
    return root
